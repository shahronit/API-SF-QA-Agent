'use strict';
/**
 * Frontend HTTP / Postman scenarios: smoke the configured base URL and
 * promote matching collection requests into the same executable suite.
 */
const { importCollection } = require('./postman');
const { repo } = require('../db');
const { localFiles } = require('../connectors/postman');

const FRONTEND_RX = /\b(front-?end|bff|backend[- ]for[- ]frontend|storefront|web ?app|mobile app|postman|http api|rest endpoint|middleware|api gateway|gateway|headless)\b/i;
const PLATFORM_EXPORT_RX = /^Generated by Salesforce API QA Platform/;

// Words that appear in almost every story or request title and say nothing about relevance.
const GENERIC = new Set([
  'about', 'after', 'again', 'already', 'before', 'being', 'between', 'call', 'calls', 'clear', 'create', 'created',
  'creates', 'data', 'delete', 'deleted', 'does', 'each', 'either', 'equal', 'equals', 'error', 'every', 'field',
  'fields', 'from', 'get', 'given', 'have', 'http', 'https', 'into', 'invalid', 'json', 'list', 'make', 'must',
  'only', 'other', 'patch', 'payload', 'post', 'provided', 'query', 'read', 'record', 'reject', 'rejected', 'request',
  'required', 'response', 'retrieve', 'return', 'returns', 'salesforce', 'service', 'services', 'should', 'status',
  'submit', 'submitted', 'that', 'their', 'them', 'then', 'there', 'these', 'they', 'this', 'through', 'update',
  'updated', 'user', 'users', 'using', 'valid', 'value', 'values', 'version', 'when', 'where', 'which', 'with',
  'within', 'without', 'baseurl', 'apiversion', 'data/v', 'sobject', 'sobjects', 'test', 'tests', 'true', 'false',
]);

function httpCfg(project) {
  return ((project && project.integrationConfig) || {}).http || {};
}

function storyBlob(story) {
  return `${story.summary || ''} ${story.description || ''} ${story.acceptanceCriteria || ''}`.toLowerCase();
}

const stem = (w) => w.replace(/(ies)$/, 'y').replace(/(?<=[a-z]{3})s$/, '');

function terms(text) {
  const out = new Set();
  for (const w of String(text || '').toLowerCase().split(/[^a-z0-9_]+/)) {
    if (w.length < 4 || /^\d+$/.test(w) || GENERIC.has(w)) continue;
    const s = stem(w);
    if (!GENERIC.has(s)) out.add(s);
  }
  return out;
}

function pathSegments(endpoint) {
  return new Set(String(endpoint || '').split('?')[0].toLowerCase().split(/[/{}.:-]+/).filter((s) => s.length >= 4).map(stem));
}

/** A request is relevant when it shares two meaningful words with the story, or one of its path segments. */
function relevance(storyTerms, draft) {
  const hay = terms(`${draft.title} ${draft.endpoint}`);
  const segs = pathSegments(draft.endpoint);
  let shared = 0;
  let segHit = false;
  for (const t of storyTerms) {
    if (hay.has(t)) shared++;
    if (segs.has(t)) segHit = true;
  }
  return shared >= 2 || segHit;
}

function collectionsFor(project) {
  const out = [];
  try {
    for (const row of repo.find('collections', 'projectId = $p', { p: project.id })) {
      if (row.content) out.push({ name: row.name, collection: row.content, source: row.source });
    }
  } catch { /* db not ready in unit tests */ }
  try {
    for (const f of localFiles()) {
      // Our own exports mirror test cases that already exist (often of another project) — never re-import them.
      if (PLATFORM_EXPORT_RX.test(String((f.collection.info && f.collection.info.description) || ''))) continue;
      out.push({ name: f.name, collection: f.collection, source: 'local' });
    }
  } catch { /* no files */ }
  return out;
}

function draftsFromCollections(project, story, opts = {}) {
  const blob = storyBlob(story);
  const storyTerms = terms(blob);
  const frontend = opts.frontend !== undefined ? opts.frontend : FRONTEND_RX.test(blob);
  const commerce = Boolean(opts.commerce);
  const relevant = [];
  const fallback = [];
  for (const col of collectionsFor(project)) {
    let items;
    try { items = importCollection(col.collection); } catch { continue; }
    for (const d of items) {
      const draft = { ...d, collectionName: col.name };
      if (!blob.trim() || relevance(storyTerms, d)) relevant.push(draft);
      else if ((frontend && d.apiType === 'HTTP') || (commerce && (d.apiType === 'OCAPI' || d.apiType === 'SCAPI'))) fallback.push(draft);
    }
  }
  return (relevant.length ? relevant : fallback).slice(0, 25);
}

function httpScenarios(b, analysis) {
  const project = b.project;
  const cfg = httpCfg(project);
  const base = String(cfg.baseUrl || '').replace(/\/$/, '');
  const frontend = FRONTEND_RX.test(storyBlob(b.story));
  const commerce = (analysis.apiTypes || []).some((t) => /Commerce Cloud/i.test(t));
  const drafts = draftsFromCollections(project, b.story, { frontend, commerce });
  const httpDrafts = drafts.filter((d) => d.apiType === 'HTTP' || (!/\/services\//.test(d.endpoint) && !/\/dw\//.test(d.endpoint)));

  if (base && (frontend || httpDrafts.length)) {
    const s = b.scenario('Frontend HTTP — base URL smoke', 'Functional', 'HTTP', null, `Live GET against the configured frontend origin ${base}.`);
    b.add(s, {
      apiType: 'HTTP', title: `GET ${base}/ (frontend origin)`, method: 'GET', endpoint: `${base}/`,
      assertions: [{ type: 'status', op: 'lt', expected: 500 }, { type: 'responseTime', op: 'lt', expected: b.sla }],
      tags: ['frontend', 'http-smoke'],
    });
    b.add(s, {
      apiType: 'HTTP', testType: 'Security', title: 'Frontend origin without a bearer token', method: 'GET', endpoint: `${base}/`,
      auth: 'none', assertions: [{ type: 'status', op: 'in', expected: [200, 401, 403] }],
      tags: ['frontend', 'authentication'],
    });
  } else if (frontend && httpDrafts.length === 0) {
    analysis.gaps.push({ label: 'RECOMMENDED', text: 'Story mentions a frontend/HTTP API but no base URL or matching collection request was found. Set Connections → Postman / HTTP base URL or import a collection.' });
  }

  if (httpDrafts.length) {
    const s = b.scenario('Frontend HTTP / Postman — collection requests', 'Integration', 'HTTP', null, 'Executable requests taken from imported or local Postman collections (same runner as Salesforce tests).');
    for (const d of httpDrafts.slice(0, 15)) {
      b.add(s, {
        apiType: d.apiType === 'REST' ? 'HTTP' : d.apiType,
        title: d.title,
        method: d.method,
        endpoint: d.endpoint,
        query: d.query || {},
        headers: d.headers || {},
        body: d.body,
        bodyRaw: d.bodyRaw,
        auth: d.auth || 'default',
        assertions: d.assertions && d.assertions.length ? d.assertions : [{ type: 'status', op: 'lt', expected: 400 }],
        tags: ['frontend', 'imported'],
        description: d.description,
      });
    }
  }
}

module.exports = { httpScenarios, draftsFromCollections, httpCfg, relevance, terms };
