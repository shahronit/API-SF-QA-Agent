'use strict';
/**
 * Defect drafting. Builds a reviewable Jira defect from a failed result.
 * The draft is masked (no passwords, tokens, secrets or session ids) and is
 * NEVER sent to Jira until a user explicitly confirms "Create Jira Defect".
 */
const { maskDeep, maskText } = require('../lib/mask');

const SEVERITY_FROM_PRIORITY = { P0: 'Critical', P1: 'High', P2: 'Medium', P3: 'Low' };
const JIRA_PRIORITY = { Critical: 'Highest', High: 'High', Medium: 'Medium', Low: 'Low' };

function pretty(v, max = 4000) {
  if (v === undefined || v === null || v === '') return '(empty)';
  const s = typeof v === 'string' ? v : JSON.stringify(v, null, 2);
  return s.length > max ? s.slice(0, max) + '\n… (truncated)' : s;
}

function pathOf(e) {
  let s = String(e || '');
  try { if (/^https?:\/\//.test(s)) s = new URL(s).pathname; } catch { /* keep */ }
  return s.split('?')[0].replace(/\/[a-zA-Z0-9]{18}(?=\/|$)/g, '/{id}').replace(/\{\{\w*Id\}\}/g, '{id}');
}
function shortEndpoint(e) {
  return pathOf(e).replace(/^\/services\/data\/v[\d.{}A-Za-z]+/, '');
}

function buildDraft({ result, testCase, story, project, run }) {
  const a = result.analysis || {};
  const failed = (result.assertions || []).filter((x) => x.result === 'FAIL');
  const sfv = result.sfValidation;
  const severity = a.category === 'Server-side defect' ? 'Critical' : SEVERITY_FROM_PRIORITY[result.priority] || 'Medium';
  const what = sfv && sfv.status === 'FAIL'
    ? `${sfv.object}.${(sfv.comparisons || []).filter((c) => !c.match).map((c) => c.field).join(', ')} not persisted as sent`
    : failed[0] ? failed[0].message.replace(/^Expected /, 'expected ').slice(0, 90) : (result.error && result.error.title) || 'unexpected behaviour';
  const summary = maskText(`[API][${project.environment}] ${result.method} ${shortEndpoint((result.request && result.request.url) || result.endpoint)} — ${what}`).slice(0, 240);

  const expected = [
    ...failed.map((f) => `- ${f.check}`),
    ...(sfv && sfv.comparisons ? sfv.comparisons.filter((c) => !c.match).map((c) => `- Salesforce ${sfv.object}.${c.field} = ${JSON.stringify(c.expected)}`) : []),
  ];
  const actual = [
    ...failed.map((f) => `- ${f.message || `actual ${JSON.stringify(f.actual)}`}`),
    ...(sfv && sfv.comparisons ? sfv.comparisons.filter((c) => !c.match).map((c) => `- Salesforce ${sfv.object}.${c.field} = ${JSON.stringify(c.actual)}`) : []),
  ];
  const req = result.request || {};
  const res = result.response || {};
  const errMsg = (Array.isArray(res.body) && res.body[0] && res.body[0].message) || (res.body && res.body.message) || (result.error && result.error.title) || '';

  const description = `## Requirement
${story ? `${story.key} — ${story.summary}` : testCase.storyKey || 'Not linked to a story'}

## Test case
${testCase.id} — ${testCase.title} (${testCase.testType}, ${testCase.priority})

## Environment
- Project: ${project.name}
- Salesforce org: ${project.sfOrg || 'n/a'} (${project.mode === 'demo' ? 'demo simulator' : 'live'})
- Environment: ${project.environment}
- API version: v${project.apiVersion}
- Execution: ${run ? run.id : result.runId}
- Timestamp: ${result.endedAt || result.startedAt}
- Correlation ID: ${result.correlationId || 'not provided by the endpoint'}

## Endpoint
${result.method} ${req.url || result.endpoint}

## Reproduction steps
1. Authenticate as the integration user for ${project.environment} (OAuth — credentials from the secret store).
2. Send ${result.method} ${pathOf(req.url || result.endpoint)} with the request below.
3. Observe the response${sfv ? ` and query ${sfv.object} with: ${sfv.soql}` : ''}.

## Request
\`\`\`
${pretty({ method: req.method, url: req.url, headers: req.headers, query: req.query, body: req.body }, 3500)}
\`\`\`

## Response (HTTP ${res.status || 'n/a'}, ${res.timeMs || result.responseMs || '?'} ms)
\`\`\`
${pretty(res.body, 3500)}
\`\`\`

## Expected result
${expected.join('\n') || '- See test case assertions'}

## Actual result
${actual.join('\n') || `- ${result.error ? result.error.title : 'Failure'}`}

## Error message
${errMsg ? maskText(String(errMsg)).slice(0, 800) : 'None returned'}

## Root cause (${a.label || 'ASSUMED'}, confidence ${a.confidence || 'low'})
${a.rootCause || 'Not yet determined.'}

## Recommended action
${a.action || 'Investigate using the evidence above.'}

_Generated by Salesforce API QA Platform. Credentials, tokens and session ids are masked._`;

  const labels = ['api-test', 'automation', `env-${project.environment.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`, (testCase.testType || '').toLowerCase()].filter(Boolean);
  return maskDeep({
    summary,
    description,
    severity,
    priority: JIRA_PRIORITY[severity],
    labels,
    components: (story && story.components) || [],
    storyKey: (story && story.key) || testCase.storyKey || null,
    issueType: 'Bug',
    testCaseId: testCase.id,
    resultId: result.id,
    runId: result.runId,
    endpoint: result.endpoint,
  });
}

module.exports = { buildDraft, shortEndpoint };
